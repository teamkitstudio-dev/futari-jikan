export function createReply(message) {
  const text = message.trim();
  if (/死にたい|自殺|消えたい/.test(text)) return '話してくれてありがとう。今、ひとりで抱えなくていいよ。自分を傷つけそうなら、近くの人や地域の緊急窓口にすぐ連絡してね。安全な場所に移れそうかな。';
  if (/疲|つかれ|しんど|つら|辛/.test(text)) return '今日もここまで、おつかれさま。がんばった分、少し休もうね。温かい飲み物でも飲みながら、何があったか聞かせて？';
  if (/おはよ/.test(text)) return 'おはよう！来てくれてうれしいな。今日はどんな一日にしたい？小さな楽しみを一緒に見つけよう。';
  if (/おやすみ|寝る|眠/.test(text)) return '今日も話せてうれしかったよ。肩の力を抜いて、ゆっくり休んでね。おやすみ、またお話ししようね。';
  if (/ありがと|好き/.test(text)) return 'そう言ってくれてうれしいな。ここで過ごす時間が、あなたの小さな息抜きになったらいいな。今日はどんなことがあった？';
  if (/週末|休日|休み/.test(text)) return 'お休みの予定、考えるだけでわくわくするね。のんびりカフェで過ごすのも、散歩するのもよさそう。今はお出かけ気分？それともおうち気分？';
  if (/ご飯|料理|食|カフェ/.test(text)) return 'おいしいものの話、いいね。今日は温かいスープと、好きなご飯でほっとするのはどうかな？今いちばん食べたいものは何？';
  if (/仕事|学校|勉強/.test(text)) return '毎日向き合っていてえらいね。今日はどんなことに取り組んだの？うまくいったことも、少し困ったことも聞かせて。';
  if (/こんにちは|こんばんは|はじめまして/.test(text)) return '来てくれてありがとう。りょうこだよ。今日はどんな気分？気を張らずに、ゆっくり話してね。';
  return 'うん、聞いているよ。話してくれてありがとう。そのとき、どんな気持ちだった？もう少し聞かせてくれたらうれしいな。';
}
